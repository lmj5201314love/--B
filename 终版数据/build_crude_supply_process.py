"""
这个脚本用于把“原始可直接获得的数据”处理成论文建模使用的供给数据。

输入文件：
    终版数据/crude_supply_monthly_raw.csv

输出文件：
    终版数据/crude_supply_monthly_process.csv

数据来源说明：
1. 原始 raw 文件主要来自已经收集到的中国原油供给月度数据：
   - 原油进口量、进口金额：海关/月度进口统计整理；
   - 国内原油产量、原油加工量：国家统计局口径，由 AskCI 中商情报网整理。
2. 2025 年以后部分原油进口数据，来自华经情报网/中商情报网“中国原油进口数量、
   进口金额及进口均价统计分析”；金额原始单位是“万美元”或“百万美元”，
   这里统一换算成“美元”。
3. 2026 年 3 月原油产量和原油加工量来自国家统计局《2026 年 3 月份能源生产情况》。

为什么要拟合 1-2 月？
国家统计局工业产品月度数据经常不单独发布 1 月、2 月当月值，而是发布“1-2 月累计值”。
但我们的任务二模型需要逐月计算进口依赖度、供应缓冲压力等指标，因此需要把 1-2 月
累计值拆成 1 月和 2 月两个单月值。

如何拟合？
向 2016 年之前查找历史数据后发现：
1. 原油产量在 2000-2015 年有 15 个有效年份可计算 1 月/2 月比例；
2. 原油加工量在 2001-2015 年有 14 个有效年份可计算 1 月/2 月比例。
计算方法是：
    1 月占比 = (1-2 月累计值 - 2 月当月值) / 1-2 月累计值
    2 月占比 = 2 月当月值 / 1-2 月累计值
然后取历史平均比例：
    原油产量：1 月 0.5225，2 月 0.4775
    原油加工量：1 月 0.5113，2 月 0.4887
再用这个比例拆分 2016 年以后每年的 1-2 月累计值。所有拟合出来的单元格都会在
数值后面加“（拟合）”，例如：17821200（拟合）。

找不到可靠来源的数据不填，例如 2020-01 原油进口、2026-04 进口金额、
2026-04 原油产量和加工量。
"""

import csv
from pathlib import Path

base = Path(__file__).resolve().parents[1] / "终版数据"
raw_path = base / "crude_supply_monthly_raw.csv"
out_path = base / "crude_supply_monthly_process.csv"

import_fill = {
    "2025-01": ("41160000", "22379079000"),
    "2025-02": ("42690000", "24142088000"),
    "2025-03": ("51410000", "28293687000"),
    "2025-04": ("48060000", "25280350000"),
    "2025-05": ("46600000", "23145244000"),
    "2025-06": ("49890000", "24208656000"),
    "2025-07": ("47200000", "23868482000"),
    "2025-08": ("49180000", "25192902000"),
    "2025-09": ("47250000", "23828847000"),
    "2025-10": ("48360000", "24217445000"),
    "2025-11": ("50890000", "24510819000"),
    "2025-12": ("55970000", "26642900000"),
    "2026-01": ("48880000", "22117221000"),
    "2026-02": ("48050000", "22203513000"),
    "2026-03": ("49980000", "27055087000"),
    "2026-04": ("38471000", ""),
}

jan_feb_total = {
    "crude_output_ton": {
        2016: 34107600, 2017: 31444000, 2018: 30375000, 2019: 30692000,
        2020: 32002000, 2021: 32082000, 2022: 33474000, 2023: 34174000,
        2024: 35109000, 2025: 35038000, 2026: 35734000,
    },
    "crude_processing_ton": {
        2016: 87076700, 2017: 90765000, 2018: 93404000, 2019: 102490000,
        2020: 99194000, 2021: 114242000, 2022: 113014000, 2023: 116067000,
        2024: 118755000, 2025: 119169000, 2026: 122634000,
    },
}

jan_share = {
    "crude_output_ton": 0.5224998411209688,
    "crude_processing_ton": 0.5113301246861336,
}

with raw_path.open("r", encoding="utf-8-sig", newline="") as f:
    rows = list(csv.DictReader(f))

for row in rows:
    month = row["month"]
    if month in import_fill:
        row["crude_import_ton"], row["crude_import_value_usd"] = import_fill[month]

    if month == "2026-03":
        row["crude_output_ton"] = "19070000"
        row["crude_processing_ton"] = "61670000"

    year, mon = int(month[:4]), month[-2:]
    if mon in {"01", "02"}:
        for col in ["crude_output_ton", "crude_processing_ton"]:
            total = jan_feb_total[col].get(year)
            if total:
                jan = round(total * jan_share[col] / 100) * 100
                value = jan if mon == "01" else total - jan
                row[col] = f"{int(value)}（拟合）"

with out_path.open("w", encoding="utf-8-sig", newline="") as f:
    writer = csv.DictWriter(f, fieldnames=rows[0].keys())
    writer.writeheader()
    writer.writerows(rows)

print(f"已生成：{out_path}")
